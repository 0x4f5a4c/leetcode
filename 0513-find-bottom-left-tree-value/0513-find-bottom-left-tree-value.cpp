// Question Link : https://leetcode.com/problems/find-bottom-left-tree-value/

class Solution {
public:
    int findBottomLeftValue(TreeNode *root) {
        queue<TreeNode*> q;
        q.push(root);
        TreeNode *node;
        while (!q.empty()) {
            node = q.front();
            q.pop();
            if (node->right) q.push(node->right);
            if (node->left) q.push(node->left);
        }

        return node->val;
    }
};